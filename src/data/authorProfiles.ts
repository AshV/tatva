export function getAuthorProfile(slug: string, fallbackName?: string, lang: string = 'hi'): AuthorProfile {
  if (authorProfiles[slug]) {
    return authorProfiles[slug];
  }
  const themeProfile = getThemeAuthorProfile(slug, fallbackName, lang);
  return {
    ...themeProfile,
    photo: getAuthorPhotoUrl(slug, themeProfile.photo)
  };
}
